// Chapter: Conversations as tokens.
// Figure: one example conversation written in the selected model's chat format, with special
// tokens marked and the tokens that receive loss in supervised fine-tuning underlined.
(function () {
  const SYS = 'You are a helpful assistant.', USER = 'How many legs does a spider have?';
  const THINK = 'Spiders are arachnids. Arachnids have four pairs of legs, so 4 × 2 = 8.', ANSWER = 'A spider has eight legs.';
  let thinking = true;

  // Each format as a list of [text, kind]: kind 's' special token, 'm' masked text, 't' trained text, 'ts' trained special token.
  const FORMATS = {
    llama3: { name: 'Llama 3 chat format', parts: () => [
      ['<|begin_of_text|>', 's'], ['<|start_header_id|>', 's'], ['system', 'm'], ['<|end_header_id|>', 's'], [`\n\n${SYS}`, 'm'], ['<|eot_id|>', 's'],
      ['<|start_header_id|>', 's'], ['user', 'm'], ['<|end_header_id|>', 's'], [`\n\n${USER}`, 'm'], ['<|eot_id|>', 's'],
      ['<|start_header_id|>', 's'], ['assistant', 'm'], ['<|end_header_id|>', 's'], ['\n\n', 'm'], [ANSWER, 't'], ['<|eot_id|>', 'ts']] },
    llama2: { name: 'Llama 2 chat format (used by Llama-2-chat; Llama 2 70B itself is a base model)', parts: () => [
      ['<s>', 's'], ['[INST] <<SYS>>\n', 'm'], [SYS, 'm'], ['\n<</SYS>>\n\n', 'm'], [USER, 'm'], [' [/INST] ', 'm'], [ANSWER, 't'], [' </s>', 'ts']] },
    deepseek: { name: 'DeepSeek-V3 chat format', parts: () => [
      ['<｜begin▁of▁sentence｜>', 's'], [SYS, 'm'], ['<｜User｜>', 's'], [USER, 'm'], ['<｜Assistant｜>', 's'], [ANSWER, 't'], ['<｜end▁of▁sentence｜>', 'ts']] },
    chatml: { name: 'ChatML, as used by Qwen', think: true, parts: (th) => [
      ['<|im_start|>', 's'], ['system\n', 'm'], [SYS, 'm'], ['<|im_end|>', 's'], ['\n', 'm'],
      ['<|im_start|>', 's'], ['user\n', 'm'], [USER, 'm'], ['<|im_end|>', 's'], ['\n', 'm'],
      ['<|im_start|>', 's'], ['assistant\n', 'm'], ...(th ? [['<think>', 'ts'], [`\n${THINK}\n`, 't'], ['</think>', 'ts'], ['\n\n', 't']] : []), [ANSWER, 't'], ['<|im_end|>', 'ts']] },
    harmony: { name: 'harmony format (gpt-oss)', think: true, parts: (th) => [
      ['<|start|>', 's'], ['system', 'm'], ['<|message|>', 's'], [`${SYS}\nReasoning: medium`, 'm'], ['<|end|>', 's'],
      ['<|start|>', 's'], ['user', 'm'], ['<|message|>', 's'], [USER, 'm'], ['<|end|>', 's'],
      ...(th ? [['<|start|>', 'ts'], ['assistant', 't'], ['<|channel|>', 'ts'], ['analysis', 't'], ['<|message|>', 'ts'], [THINK, 't'], ['<|end|>', 'ts']] : []),
      ['<|start|>', 'ts'], ['assistant', 't'], ['<|channel|>', 'ts'], ['final', 't'], ['<|message|>', 'ts'], [ANSWER, 't'], ['<|return|>', 'ts']] },
  };

  function view(m) {
    const f = FORMATS[m.chat], parts = f.parts(thinking && f.think);
    const html = parts.map(([t, k]) => `<span class="cv-${k}">${esc(t).replace(/\n/g, '↵\n')}</span>`).join('');
    const trained = parts.filter(([, k]) => k === 't' || k === 'ts').reduce((n, [t]) => n + t.length, 0);
    const all = parts.reduce((n, [t]) => n + t.length, 0);
    return `${f.think ? `<p class="controls"><label><input type="checkbox" id="cv-think"${thinking ? ' checked' : ''}> include a reasoning section before the answer</label></p>` : ''}
      <pre class="doc conv">${html}</pre>
      <p class="caption">${esc(f.name)}. Bold: special tokens, each one vocabulary entry that ordinary text never produces. Underlined: the tokens that receive loss in supervised fine-tuning (${fmtPct(trained, all)} of the characters here); system and user tokens are part of the input but are not predicted. At inference the server writes everything up to and including the assistant header, and the model generates the rest until its end token.</p>`;
  }

  function render(ctx) {
    const m = ctx.m;
    const lead = `<p class="lead">Pre-training produces a model that continues documents. Post-training turns it into an assistant by continuing the same next-token training on conversations: example dialogues written by people or generated by other models, each a system message, user turns and assistant replies. A conversation is written as one token sequence with special tokens that mark where each message starts and ends and who wrote it. The model learns to produce the assistant parts, including the token that ends its turn.</p>`;
    if (!m.chat) {
      const others = window.MODELS.filter((x) => x.chat).map((x) => `<a href="#" data-model="${x.id}">${esc(x.short)}</a>`).join(', ');
      return `${lead}<p><b>${esc(m.name)}</b> was released as a base model without a chat format: it continues whatever text it is given. Select a post-trained model to see its format: ${others}.</p>`;
    }
    return `${lead}
      <p><b>${esc(m.name)}</b> uses the ${esc(FORMATS[m.chat].name)}. The template is stored with the tokenizer (chat_template in tokenizer_config.json) and applied by the inference server.</p>
      <h2>One conversation, written as tokens</h2>${view(m)}
      <h2>What the format carries</h2>
      <ul class="formulas">
        <li><b>Roles.</b> System, user and assistant messages are delimited by special tokens, so text inside a message cannot be read as a role marker.</li>
        <li><b>Turn ends.</b> The assistant's end token is trained like any other token; generation stops when the model produces it.</li>
        <li><b>Reasoning.</b> Models trained to reason write a separate section before the answer: Qwen inside &lt;think&gt; tags, gpt-oss in an analysis channel. In multi-turn conversations, earlier reasoning sections are usually dropped from the context.</li>
        <li><b>Tool calls</b> are further special sections in the assistant's turn; the tool's output returns as another message (Context, tools and thinking).</li>
      </ul>
      <details class="more"><summary>Loss</summary><ul class="formulas">
        <li>Supervised fine-tuning loss: L = −(1/|A|) Σ<sub>t ∈ A</sub> ln p(x<sub>t</sub> | x<sub>&lt;t</sub>), where A is the set of positions inside assistant messages. The other positions are in the input, but their predictions are not trained.</li>
        <li>The data is far smaller than pre-training data, but the same next-token objective applies; the InstructGPT work (2022) trained on about 13,000 written demonstrations.</li>
      </ul></details>
      <p class="sources">Sources: <a href="https://arxiv.org/abs/2203.02155" target="_blank" rel="noreferrer">InstructGPT (Ouyang et al., 2022)</a> · <a href="https://github.com/openai/harmony" target="_blank" rel="noreferrer">harmony format</a> · <a href="${esc(m.source.replace('config.json', 'tokenizer_config.json'))}" target="_blank" rel="noreferrer">${esc(m.name)} tokenizer_config.json</a>.</p>`;
  }

  function mount(root, ctx, rerender) {
    const cb = root.querySelector('#cv-think');
    if (cb) cb.addEventListener('change', () => { thinking = cb.checked; rerender(); });
  }

  (window.CHAPTERS = window.CHAPTERS || {}).chat = { render, mount };
})();
