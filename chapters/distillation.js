// Chapter: Distillation.
// Figures: (1) the training target at one position: one-hot next token versus the teacher's full
// distribution; (2) the cost of producing distillation data with the selected model as the teacher.
(function () {
  const CAND = [[' eight', 0.62], [' 8', 0.21], [' many', 0.07], [' six', 0.04], [' four', 0.02], [' ten', 0.01]];
  let nTok = 1e9;

  function figTargets(W) {
    const lw = 90, colW = (W - lw) / 2 - 10, rowH = 20;
    let s = `<text x="${lw}" y="12" class="name">hard target (generated text)</text><text x="${lw + colW + 20}" y="12" class="name">soft target (teacher distribution)</text>`;
    CAND.forEach(([t, p], i) => {
      const y = 24 + i * rowH;
      s += `<text x="${lw - 8}" y="${y + 13}" text-anchor="end" class="tok">${showTok(t)}</text>`
        + `<rect x="${lw}" y="${y + 3}" width="${i === 0 ? colW * 0.9 : 0.5}" height="13" class="pkeep"/>`
        + `<rect x="${lw + colW + 20}" y="${y + 3}" width="${Math.max(0.5, p * colW * 0.9 / 0.62)}" height="13" class="pkeep"/>`
        + `<text x="${lw + colW + 24 + p * colW * 0.9 / 0.62}" y="${y + 13}" class="val">${p.toFixed(2)}</text>`;
    });
    return `${figure(s, W, 24 + CAND.length * rowH + 4, 'hard and soft targets')}
      <p class="caption">Context “A spider has” (illustrative probabilities). Training on generated text gives one target token per position. Matching the teacher's distribution gives a target for every vocabulary entry; the student also learns which wrong answers are close.</p>`;
  }

  function figCost(m) {
    const P = params(m), gen = 2 * P.matmul * nTok, store = nTok * 64 * (4 + 2);
    return `<p class="controls"><label class="nw">tokens of teacher output <select id="di-n">${[1e8, 1e9, 1e10, 1e11].map((v) => `<option value="${v}"${v === nTok ? ' selected' : ''}>${fmtParams(v)}</option>`).join('')}</select></label></p>
      <table class="data"><tbody>
        <tr><td>Teacher</td><td>${esc(m.name)}, ${fmtParams(P.matmul)} weights multiplied per token</td></tr>
        <tr><td>Generating the text</td><td class="r">≈ ${fmtFlops(gen)} (2 FLOPs per weight per token, before attention)</td></tr>
        <tr><td>Storing hard targets</td><td class="r">${fmtBytes(nTok * (m.vocab <= 65536 ? 2 : 4))} of token IDs</td></tr>
        <tr><td>Storing soft targets, top 64 entries</td><td class="r">${fmtBytes(store)} (a 32-bit ID and a 16-bit probability each)</td></tr>
        <tr><td>Storing full distributions</td><td class="r">${fmtBytes(nTok * m.vocab * 2)} (${fmtN(m.vocab)} BF16 values per token)</td></tr>
      </tbody></table>
      <p class="caption">Full distributions are too large to store at scale, so soft-target distillation keeps the top entries or runs teacher and student together.</p>`;
  }

  function render(ctx) {
    const m = ctx.m, W = ctx.width;
    return `
      <p class="lead">A smaller model can be trained on the outputs of a larger one, its teacher. With hard targets, the teacher generates text, for example worked solutions, and the student is fine-tuned on that text with the ordinary next-token loss. With soft targets, the student is trained to match the teacher's whole probability distribution at every position. The student ends up with a fraction of the parameters and some of the teacher's capability.</p>
      <h2>What the student is trained to predict</h2>${figTargets(W)}
      <h2>Cost of the teacher's output</h2>${figCost(m)}
      <h2>Published examples</h2>
      <ul class="formulas">
        <li><b>DeepSeek-R1 distilled models:</b> Qwen2.5 and Llama 3 models from 1.5B to 70B parameters fine-tuned on about 800,000 samples generated with DeepSeek-R1 (hard targets).</li>
        <li><b>DeepSeek-V3:</b> its post-training includes reasoning data generated by DeepSeek-R1 models.</li>
        <li><b>Qwen3:</b> the small models were trained from the large ones (strong-to-weak distillation) instead of with the full reinforcement-learning pipeline.</li>
        <li><b>Gemma 2:</b> the 2B and 9B models were pre-trained on the teacher's distributions instead of on next tokens (soft targets).</li>
      </ul>
      <details class="more"><summary>Formulas</summary><ul class="formulas">
        <li>Hard targets: L = −Σ<sub>t</sub> ln p<sub>student</sub>(x<sub>t</sub> | x<sub>&lt;t</sub>) on teacher-generated x.</li>
        <li>Soft targets: L = Σ<sub>t</sub> KL(p<sub>teacher</sub>(· | x<sub>&lt;t</sub>) ‖ p<sub>student</sub>(· | x<sub>&lt;t</sub>)), often with both distributions taken at a temperature above 1.</li>
      </ul></details>
      <p class="sources">Sources: <a href="https://arxiv.org/abs/1503.02531" target="_blank" rel="noreferrer">Distilling the Knowledge in a Neural Network (Hinton et al., 2015)</a> · <a href="https://arxiv.org/abs/2501.12948" target="_blank" rel="noreferrer">DeepSeek-R1</a> · <a href="https://arxiv.org/abs/2412.19437" target="_blank" rel="noreferrer">DeepSeek-V3 report</a> · <a href="https://arxiv.org/abs/2505.09388" target="_blank" rel="noreferrer">Qwen3 technical report</a> · <a href="https://arxiv.org/abs/2408.00118" target="_blank" rel="noreferrer">Gemma 2</a>.</p>`;
  }

  function mount(root, ctx, rerender) {
    root.querySelector('#di-n').addEventListener('change', (e) => { nTok = Number(e.target.value); rerender(); });
  }

  (window.CHAPTERS = window.CHAPTERS || {}).distillation = { render, mount };
})();
